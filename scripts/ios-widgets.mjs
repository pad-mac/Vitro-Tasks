// Adds the home screen widgets (ios/widgets) to the Xcode project that
// `tauri ios init` generates: a WidgetKit extension target, embedded in the
// app, and regenerates the project. Run in CI after `tauri ios init --ci`.
//
// The extension comes in through XcodeGen's `include` (specs are merged
// additively, so the app target only gains the dependency). Both share the
// app group "group.app.vitro.tasks"; the unsigned build carries it in an
// ad-hoc signature (see .github/workflows/ios.yml), which is where SideStore
// reads the entitlements it asks for when it signs the app.
import { execFileSync } from "node:child_process";
import { readFileSync, writeFileSync } from "node:fs";
import { join } from "node:path";

const root = new URL("..", import.meta.url).pathname;
const apple = join(root, "src-tauri/gen/apple");
const specPath = join(apple, "project.yml");
const spec = readFileSync(specPath, "utf8");
const version = JSON.parse(readFileSync(join(root, "src-tauri/tauri.conf.json"), "utf8")).version;

const app = spec.match(/^ {2}([^\s:]+_iOS):\s*$/m)?.[1];
if (!app) throw new Error("no <name>_iOS target in project.yml");

const widgets = `# Generated by scripts/ios-widgets.mjs: the widget extension, embedded in ${app}.
targets:
  VitroWidgets:
    type: app-extension
    platform: iOS
    deploymentTarget: "17.0"
    sources:
      - path: ../../../ios/widgets
    info:
      path: VitroWidgets/Info.plist
      properties:
        CFBundleDisplayName: Vitro Tasks
        CFBundleShortVersionString: "${version}"
        CFBundleVersion: "${version}"
        NSExtension:
          NSExtensionPointIdentifier: com.apple.widgetkit-extension
    entitlements:
      path: VitroWidgets/VitroWidgets.entitlements
      properties:
        com.apple.security.application-groups:
          - group.app.vitro.tasks
    settings:
      base:
        PRODUCT_BUNDLE_IDENTIFIER: app.vitro.tasks.widgets
        PRODUCT_NAME: VitroWidgets
        SWIFT_VERSION: "5.0"
        TARGETED_DEVICE_FAMILY: "1,2"
        GENERATE_INFOPLIST_FILE: NO
        SKIP_INSTALL: YES
        ENABLE_BITCODE: NO
        LD_RUNPATH_SEARCH_PATHS: "$(inherited) @executable_path/Frameworks @executable_path/../../Frameworks"
    dependencies:
      - sdk: WidgetKit.framework
      - sdk: SwiftUI.framework
      - sdk: AppIntents.framework
  ${app}:
    dependencies:
      - target: VitroWidgets
      - sdk: WidgetKit.framework
`;
writeFileSync(join(apple, "widgets.yml"), widgets);

if (!/^include:/m.test(spec)) writeFileSync(specPath, `${spec.trimEnd()}\ninclude:\n  - widgets.yml\n`);
else if (!spec.includes("widgets.yml")) throw new Error("project.yml has its own include: add widgets.yml by hand");

execFileSync("xcodegen", ["generate", "--spec", specPath], { cwd: apple, stdio: "inherit" });
console.log(`widgets: VitroWidgets added to ${app} (${version})`);
